"""orchard/speedwatch.py: is a model server decoding as fast as it did when it was healthy?

Why a client-side measurement: on 2026-10-17 the server log's "Avg generation throughput" was read as decode speed.
It is tokens over the whole 10 s window, so an agent's short tool-call turns made a healthy server read 5 to 8 tok/s
(measured idle at 38.7 tok/s the same hour). The watcher asks for a fixed answer and divides the tokens the server says
it generated by the seconds the request took.
"""
import json

import pytest

from orchard import speedwatch as sw


def fake_post(tokens=300, seconds=10.0, now=None):
    """A post function that answers like a server and advances a fake clock by `seconds`."""
    now = now if now is not None else [0.0]

    def post(url, body, timeout):
        post.calls.append((url, body, timeout))
        now[0] += seconds
        return {"choices": [{"message": {"content": "x"}}], "usage": {"completion_tokens": tokens}}
    post.calls = []
    post.now = now
    return post


def measure(post, **kw):
    return sw.measure("http://127.0.0.1:8011/v1", "m", post=post, clock=lambda: post.now[0], **kw)


# ---- the measurement ------------------------------------------------------------------------------------------

def test_tokens_per_second_is_the_servers_token_count_over_the_request_time():
    s = measure(fake_post(tokens=400, seconds=10.0))
    assert s.tokens == 400 and s.seconds == 10.0 and s.tok_s == pytest.approx(40.0)


def test_the_request_is_greedy_with_thinking_off_and_a_fixed_budget():
    post = fake_post()
    measure(post)
    url, body, timeout = post.calls[0]
    assert url == "http://127.0.0.1:8011/v1/chat/completions"           # an endpoint ending in /v1 is not doubled
    assert body["temperature"] == 0 and body["max_tokens"] == sw.MAX_TOKENS and body["stream"] is False
    assert body["chat_template_kwargs"] == {"enable_thinking": False} and body["model"] == "m"
    assert body["messages"][0]["content"] == sw.PROMPT and timeout == sw.TIMEOUT_S


def test_an_endpoint_without_v1_gets_it_added_once():
    post = fake_post()
    sw.measure("http://127.0.0.1:8001", "m", post=post, clock=lambda: post.now[0])
    sw.measure("http://127.0.0.1:8001/", "m", post=post, clock=lambda: post.now[0])
    assert [c[0] for c in post.calls] == ["http://127.0.0.1:8001/v1/chat/completions"] * 2


def test_an_answer_too_short_to_time_is_refused_not_scored():
    with pytest.raises(sw.SpeedError, match="only 40 tokens"):
        measure(fake_post(tokens=40, seconds=1.0))


@pytest.mark.parametrize("data", [{}, {"usage": {}}, {"usage": {"completion_tokens": "many"}}, {"usage": {"completion_tokens": True}}])
def test_a_reply_without_a_usable_token_count_is_an_error(data):
    with pytest.raises(sw.SpeedError):
        sw.measure("http://h/v1", "m", post=lambda *a: data, clock=lambda: 0.0)


def test_a_failed_request_is_a_speed_error_that_names_the_url():
    def boom(url, body, timeout):
        raise OSError("connection refused")
    with pytest.raises(sw.SpeedError, match="connection refused") as err:
        sw.measure("http://127.0.0.1:8011/v1", "m", post=boom, clock=lambda: 0.0)
    assert "127.0.0.1:8011" in str(err.value)


def test_zero_seconds_is_an_error_not_a_division():
    with pytest.raises(sw.SpeedError):
        sw.measure("http://h/v1", "m", post=lambda *a: {"usage": {"completion_tokens": 300}}, clock=lambda: 5.0)


# ---- the verdict ----------------------------------------------------------------------------------------------

def test_no_baseline_means_unknown_and_says_the_sample_becomes_it():
    v = sw.judge([38.7], None)
    assert v.state == "unknown" and "becomes the baseline" in v.message


def test_a_sample_near_the_baseline_is_ok():
    v = sw.judge([37.0], 38.7)
    assert v.state == "ok" and v.ratio == pytest.approx(37.0 / 38.7)


def test_the_boundary_is_exactly_the_slow_ratio():
    base = 40.0
    assert sw.judge([base * sw.SLOW_RATIO] * 3, base).state == "ok"                 # at the ratio is not below it
    assert sw.judge([base * sw.SLOW_RATIO - 0.01] * 3, base).state == "slow"


def test_one_or_two_low_samples_are_suspect_not_slow():
    assert sw.judge([10.0], 38.7).state == "suspect"
    assert sw.judge([38.0, 10.0, 11.0], 38.7).state == "suspect"                     # the oldest of the last three is fine


def test_slow_needs_the_last_consecutive_samples_all_low_and_ignores_older_ones():
    assert sw.judge([38.0, 9.0, 10.0, 11.0], 38.7).state == "slow"
    assert sw.judge([9.0, 10.0, 38.0], 38.7).state == "ok"                           # the newest is fine
    assert sw.judge([9.0, 38.0, 10.0], 38.7).state == "suspect"


def test_the_slow_message_gives_the_numbers_and_says_the_restart_is_a_person_s_call():
    v = sw.judge([9.0, 10.0, 11.0], 38.7)
    assert "11.0 tok/s" in v.message and "38.7" in v.message and "28%" in v.message          # the newest sample, 11 of 38.7
    assert "restart" in v.message and "other clients" in v.message.lower() and "--reset-baseline" in v.message


def test_with_no_samples_there_is_nothing_to_judge():
    with pytest.raises(ValueError):
        sw.judge([], 38.7)


# ---- the baseline store ---------------------------------------------------------------------------------------

def test_the_baseline_is_keyed_by_model_and_endpoint(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://127.0.0.1:8011/v1", "coder", 38.7)
    assert store.get("http://127.0.0.1:8011/v1", "coder") == 38.7
    assert store.get("http://127.0.0.1:8011/v1", "other-model") is None
    assert store.get("http://127.0.0.1:8001/v1", "coder") is None
    # one model reached with and without a trailing slash is one key
    assert store.get("http://127.0.0.1:8011/v1/", "coder") == 38.7


def test_the_baseline_only_goes_up_and_survives_a_reload(tmp_path):
    path = tmp_path / "sub" / "b.json"
    store = sw.Baselines(path)
    assert store.update("http://h/v1", "m", 30.0) == 30.0
    assert store.update("http://h/v1", "m", 38.7) == 38.7
    assert store.update("http://h/v1", "m", 9.0) == 38.7
    assert sw.Baselines(path).get("http://h/v1", "m") == 38.7
    assert json.loads(path.read_text())["http://h/v1 m"]["tok_s"] == 38.7


def test_reset_forgets_one_key_only(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://h/v1", "a", 10.0)
    store.update("http://h/v1", "b", 20.0)
    store.reset("http://h/v1", "a")
    assert store.get("http://h/v1", "a") is None and store.get("http://h/v1", "b") == 20.0
    store.reset("http://h/v1", "never-set")                                           # not an error


@pytest.mark.parametrize("text", ["", "{", "[]", '{"k": 3}', '{"k": {"tok_s": "fast"}}', '{"k": {"tok_s": -1}}',
                                  '{"k": {"tok_s": true}}'])
def test_an_unreadable_or_odd_baseline_file_is_ignored_not_trusted(tmp_path, text):
    path = tmp_path / "b.json"
    path.write_text(text)
    store = sw.Baselines(path)
    assert store.get("http://h/v1", "m") is None
    assert store.update("http://h/v1", "m", 30.0) == 30.0                              # and it can be overwritten
    assert sw.Baselines(path).get("http://h/v1", "m") == 30.0


def test_a_missing_directory_is_created_and_a_write_is_atomic(tmp_path):
    path = tmp_path / "a" / "b" / "base.json"
    sw.Baselines(path).update("http://h/v1", "m", 5.0)
    assert path.is_file() and not list(path.parent.glob("*.tmp*"))


# ---- check: measure, judge, learn ------------------------------------------------------------------------------

def test_check_learns_a_baseline_from_the_first_sample_and_reports_unknown(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    post = fake_post(tokens=400, seconds=10.0)
    r = sw.check("http://h/v1", "m", store, history=[], post=post, clock=lambda: post.now[0])
    assert r.verdict.state == "unknown" and store.get("http://h/v1", "m") == pytest.approx(40.0)


def test_check_does_not_lower_the_baseline_on_a_slow_sample_and_accumulates_history(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://h/v1", "m", 40.0)
    history = []
    for _ in range(3):
        post = fake_post(tokens=300, seconds=30.0)                                    # 10 tok/s
        r = sw.check("http://h/v1", "m", store, history=history, post=post, clock=lambda p=post: p.now[0])
    assert r.verdict.state == "slow" and history == [pytest.approx(10.0)] * 3
    assert store.get("http://h/v1", "m") == 40.0


def test_check_raises_the_baseline_when_the_server_is_faster_than_ever(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://h/v1", "m", 30.0)
    post = fake_post(tokens=400, seconds=10.0)
    r = sw.check("http://h/v1", "m", store, history=[], post=post, clock=lambda: post.now[0])
    assert r.verdict.state == "ok" and store.get("http://h/v1", "m") == pytest.approx(40.0)


def test_a_baseline_given_on_the_command_line_beats_the_stored_one_and_is_not_stored(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://h/v1", "m", 40.0)
    post = fake_post(tokens=300, seconds=10.0)                                         # 30 tok/s
    r = sw.check("http://h/v1", "m", store, history=[], baseline=25.0, post=post, clock=lambda: post.now[0])
    assert r.verdict.state == "ok" and r.verdict.baseline == 25.0 and store.get("http://h/v1", "m") == 40.0


def test_a_given_baseline_is_not_stored_even_when_the_sample_is_faster_than_the_stored_one(tmp_path):
    store = sw.Baselines(tmp_path / "b.json")
    store.update("http://h/v1", "m", 30.0)
    post = fake_post(tokens=450, seconds=10.0)                                         # 45 tok/s
    sw.check("http://h/v1", "m", store, history=[], baseline=25.0, post=post, clock=lambda: post.now[0])
    assert store.get("http://h/v1", "m") == 30.0
